<#
.SYNOPSIS
    Adds (or removes) Microsoft Defender Antivirus path exclusions for the
    QCompress project.

.DESCRIPTION
    Builds and installs churn a lot of files: `bun install` unpacks thousands
    of packages, `bun run build` rewrites the entire build directory, and the
    test suites generate hundreds of PDF renders. Defender inspects every new
    write, which shows up as sustained CPU in MsMpEng while nothing is
    actually wrong.

    This excludes only four paths inside one project:

        node_modules      third-party packages, restored by `bun install`
        build             generated output, rebuilt by `bun run build`
        .svelte-kit       generated output, rebuilt by `bun run check`/`build`
        scripts/fixtures  test PDFs, regenerated by `bun run fixtures`

    None of these are hand-written source, so nothing unique is lost by not
    scanning them.

.SECURITY
    Excluded paths are NOT scanned, including when you open a file from them.
    Run a full scan after any suspicious download, and do not add exclusions
    for directories you did not create. Use -Remove to undo.

.PARAMETER ProjectPath
    The project root. Defaults to the folder containing this script's parent.

.PARAMETER Remove
    Remove the exclusions instead of adding them.

.PARAMETER Force
    Skip the confirmation prompt.

.EXAMPLE
    .\set-defender-exclusions.ps1

.EXAMPLE
    .\set-defender-exclusions.ps1 -Remove

.NOTES
    Requires administrator. The script re-launches itself elevated.
#>

#Requires -Version 5.1

[CmdletBinding()]
param(
    [string] $ProjectPath,
    [switch] $Remove,
    [switch] $Force
)

# ── elevate ──────────────────────────────────────────────────────────────────

$isAdmin = ([Security.Principal.WindowsPrincipal] `
    [Security.Principal.WindowsIdentity]::GetCurrent()
).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)

if (-not $isAdmin) {
    Write-Host 'Administrator rights are required. Re-launching elevated...' -ForegroundColor Yellow

    $argList = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', "`"$PSCommandPath`"")
    if ($ProjectPath) { $argList += @('-ProjectPath', "`"$ProjectPath`"") }
    if ($Remove)       { $argList += '-Remove' }
    if ($Force)        { $argList += '-Force' }

    try {
        Start-Process -FilePath 'powershell.exe' -Verb RunAs -ArgumentList $argList
    } catch {
        Write-Host "Could not elevate: $($_.Exception.Message)" -ForegroundColor Red
        Write-Host 'Right-click PowerShell and choose "Run as administrator", then run this again.' -ForegroundColor Yellow
        exit 1
    }
    return
}

# ── resolve target paths ─────────────────────────────────────────────────────

if (-not $ProjectPath) {
    # <repo>\scripts\.. is the project root when this lives in scripts/tools,
    # so walk up until package.json is found.
    $dir = $PSScriptRoot
    while ($dir -and -not (Test-Path (Join-Path $dir 'package.json'))) {
        $parent = Split-Path $dir -Parent
        if ($parent -eq $dir) { break }
        $dir = $parent
    }
    if (-not $dir) {
        Write-Host 'Could not locate the project root. Pass -ProjectPath explicitly.' -ForegroundColor Red
        exit 1
    }
    $ProjectPath = $dir
}

$ProjectPath = (Resolve-Path -LiteralPath $ProjectPath).Path

$relative = @('node_modules', 'build', '.svelte-kit', 'scripts\fixtures')
$targets  = foreach ($r in $relative) { Join-Path $ProjectPath $r }
$existing = @($targets | Where-Object { Test-Path -LiteralPath $_ })

Write-Host ''
Write-Host 'QCompress - Defender exclusions' -ForegroundColor Cyan
Write-Host "  project : $ProjectPath"
Write-Host "  action  : $(if ($Remove) { 'REMOVE' } else { 'ADD' })"
Write-Host ''

# ── confirm ──────────────────────────────────────────────────────────────────

if (-not $Force) {
    Write-Host 'The following paths will be excluded from real-time scanning:'
    foreach ($p in $existing) { Write-Host "  - $p" -ForegroundColor Yellow }
    Write-Host ''
    Write-Host 'Excluded files are not scanned when opened either.' -ForegroundColor Yellow
    $answer = Read-Host 'Continue? [y/N]'
    if ($answer -notmatch '^(y|yes)$') {
        Write-Host 'Cancelled. Nothing was changed.'
        return
    }
}

# ── apply ────────────────────────────────────────────────────────────────────

$current = @(Get-MpPreference).ExclusionPath
$failed  = @()

foreach ($p in $existing) {
    # Already present (or already absent) is a success, not an error.
    if (-not $Remove -and $current -contains $p) {
        Write-Host "  = already excluded  $p" -ForegroundColor DarkGray
        continue
    }
    if ($Remove -and $current -notcontains $p) {
        Write-Host "  = not excluded      $p" -ForegroundColor DarkGray
        continue
    }

    try {
        if ($Remove) {
            Remove-MpPreference -ExclusionPath $p -ErrorAction Stop
            Write-Host "  - removed           $p" -ForegroundColor Green
        } else {
            Add-MpPreference -ExclusionPath $p -ErrorAction Stop
            Write-Host "  + added             $p" -ForegroundColor Green
        }
    } catch {
        Write-Host "  ! FAILED            $p" -ForegroundColor Red
        Write-Host "      $($_.Exception.Message.Split([char]10)[0])" -ForegroundColor DarkRed
        $failed += $p
    }
}

# ── verify ───────────────────────────────────────────────────────────────────

Write-Host ''
$final = @(Get-MpPreference).ExclusionPath
$ok = $true

foreach ($p in $existing) {
    $present = $final -contains $p
    $want    = -not $Remove
    if ($present -ne $want) {
        Write-Host "  ! verify failed: $p (present=$present, wanted=$want)" -ForegroundColor Red
        $ok = $false
    }
}

if ($ok) {
    Write-Host 'Verified: exclusions match the requested state.' -ForegroundColor Cyan
} else {
    Write-Host 'Verification failed. Check Windows Security > Virus & threat protection > Manage settings.' -ForegroundColor Red
}

if ($failed.Count) {
    Write-Host ''
    Write-Host "$($failed.Count) path(s) could not be changed." -ForegroundColor Red
    exit 1
}

Write-Host ''
Write-Host 'Current Defender exclusion paths:' -ForegroundColor DarkGray
if ($final.Count) { $final | ForEach-Object { Write-Host "  $_" -ForegroundColor DarkGray } }
else { Write-Host '  (none)' -ForegroundColor DarkGray }

Write-Host ''